// Regenerates src/abi/*.ts from the Foundry build output (run `forge build` at the repo root first).
// The ABIs are committed, so the app builds without Foundry, on Workers Builds too.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, '..', '..', 'out')
const target = join(here, '..', 'src', 'abi')

const contracts = [
  ['TradingEngine.sol', 'TradingEngine', 'tradingEngineAbi'],
  ['TradingStorage.sol', 'TradingStorage', 'tradingStorageAbi'],
  ['Vault.sol', 'Vault', 'vaultAbi'],
  ['PythChainlinkOracle.sol', 'PythChainlinkOracle', 'oracleAbi'],
  ['SpreadManager.sol', 'SpreadManager', 'spreadManagerAbi'],
  ['SolvencyManager.sol', 'SolvencyManager', 'solvencyManagerAbi'],
  ['AssistantFund.sol', 'AssistantFund', 'assistantFundAbi'],
  ['BondDepository.sol', 'BondDepository', 'bondDepositoryAbi'],
  ['SynthToken.sol', 'SynthToken', 'synthTokenAbi'],
  ['AggregatorV3Interface.sol', 'AggregatorV3Interface', 'chainlinkAbi'],
  ['DemoPyth.sol', 'DemoPyth', 'demoPythAbi'],
  ['TestnetFaucet.sol', 'TestnetFaucet', 'faucetAbi'],
  ['TestnetFaucet.sol', 'TestnetUSDC', 'testnetUsdcAbi'],
]

mkdirSync(target, { recursive: true })
const index = []
for (const [file, name, exportName] of contracts) {
  const artifact = JSON.parse(readFileSync(join(out, file, `${name}.json`), 'utf8'))
  const body =
    `// Generated by scripts/sync-abi.mjs from out/${file}/${name}.json. Do not edit.\n` +
    `export const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const\n`
  writeFileSync(join(target, `${name}.ts`), body)
  index.push(`export { ${exportName} } from './${name}'`)
  console.log(`${name}: ${artifact.abi.length} entries`)
}
writeFileSync(join(target, 'index.ts'), `// Generated by scripts/sync-abi.mjs. Do not edit.\n${index.join('\n')}\n`)
